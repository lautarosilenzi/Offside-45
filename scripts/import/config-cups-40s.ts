const ESCOBAR = {
  kind: "formato",
  text: "La jugaban los siete primeros del campeonato, casi siempre en uno o dos días y en una misma cancha, con partidos de 40 minutos. Los empates se definían por córners (y si seguían iguales, por sorteo). El campeón de liga entraba directo en semifinales.",
} as const;
const corners = (team: string, score: string, extra = "") => ({ advancedId: team, note: `Pasó por córners (${score}).${extra}` });

const escobar = (year: number, rest: Partial<TournamentConfig> & Pick<TournamentConfig, "championIds" | "summary">, list: Row[]): TournamentConfig => {
  const slug = `copa-escobar-${year}`;
  return {
    slug,
    kind: "cup",
    year,
    file: `arg-esc${String(year).slice(2)}.html`,
    competition: "Copa Escobar",
    title: `Copa Escobar ${year}`,
    tournament: "Copa Adrián C. Escobar",
    organizer: AFA,
    skip: () => true,
    extraMatches: rows(slug, list),
    notes: [ESCOBAR],
    ...rest,
  };
};

