// Copas nacionales 1941–1950. Las páginas de RSSSF de estas copas tienen formatos muy distintos entre sí
// (columnas alineadas a la derecha, fechas en la misma línea, córners en líneas sueltas): los partidos se cargan
// a mano, uno por uno, copiados de la página de RSSSF de cada edición. El control de la copa (final contra el
// índice de RSSSF, eliminados que no vuelven a jugar, participantes) corre igual.
import type { Match } from "../../lib/types";
import type { TournamentConfig } from "./config";

const AFA = "Asociación del Fútbol Argentino";

type Row = [date: string, stage: string, home: string, hg: number, ag: number, away: string, extra?: Partial<Match>];
const rows = (slug: string, list: Row[]) =>
  list.map(([date, stage, homeId, homeGoals, awayGoals, awayId, extra], i) => ({
    id: `${slug}-${String(i + 1).padStart(3, "0")}`,
    date,
    stage,
    phase: "cup" as const,
    homeId,
    awayId,
    homeGoals,
    awayGoals,
    ...extra,
  }));

